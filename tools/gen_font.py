#!/usr/bin/env python3
"""Rasterise a TTF into a 4-bit anti-aliased C font for Crystal's firmware.

Covers printable ASCII (32..126) plus a heart glyph stored at code 127, which
is the byte the chat app sends for any heart emoji.
"""

import argparse
from dataclasses import dataclass
from pathlib import Path
from typing import List, Tuple

from PIL import Image, ImageDraw, ImageFont

FIRST_CODE = 32
HEART_CODE = 127
SUPERSAMPLE = 4


@dataclass(frozen=True)
class Glyph:
    width: int
    height: int
    x_offset: int
    y_offset: int
    advance: int
    alpha: Tuple[int, ...]


def render_char(font: ImageFont.FreeTypeFont, char: str) -> Glyph:
    left, top, right, bottom = font.getbbox(char, anchor="ls")
    advance = round(font.getlength(char))
    width, height = max(0, right - left), max(0, bottom - top)
    if width == 0 or height == 0:
        return Glyph(0, 0, 0, 0, advance, ())
    image = Image.new("L", (width, height), 0)
    ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor="ls")
    return Glyph(width, height, left, top, advance, tuple(image.getdata()))


def render_heart(cap_height: int) -> Glyph:
    size = cap_height
    big = size * SUPERSAMPLE
    image = Image.new("L", (big, big), 0)
    draw = ImageDraw.Draw(image)
    radius = big // 4
    draw.ellipse((0, 0, radius * 2, radius * 2), fill=255)
    draw.ellipse((big - radius * 2, 0, big, radius * 2), fill=255)
    draw.polygon([(0, radius + radius // 3), (big, radius + radius // 3), (big // 2, big)], fill=255)
    small = image.resize((size, size), Image.LANCZOS)
    return Glyph(size, size, 1, -size, size + 3, tuple(small.getdata()))


def pack_alpha(alpha: Tuple[int, ...]) -> List[int]:
    nibbles = [value >> 4 for value in alpha] + ([0] if len(alpha) % 2 else [])
    return [(nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2)]


def build_glyphs(font: ImageFont.FreeTypeFont) -> List[Glyph]:
    glyphs = [render_char(font, chr(code)) for code in range(FIRST_CODE, HEART_CODE)]
    cap_height = -font.getbbox("H", anchor="ls")[1]
    return glyphs + [render_heart(cap_height)]


def to_c_source(glyphs: List[Glyph], ascent: int, line_height: int) -> str:
    bitmap: List[int] = []
    rows: List[str] = []
    for code, glyph in enumerate(glyphs, start=FIRST_CODE):
        rows.append(
            f"    {{{len(bitmap)}, {glyph.width}, {glyph.height}, {glyph.x_offset}, "
            f"{glyph.y_offset}, {glyph.advance}}}, // {code}"
        )
        bitmap.extend(pack_alpha(glyph.alpha))
    bitmap_lines = [
        "    " + ", ".join(f"0x{byte:02X}" for byte in bitmap[i : i + 16]) + ","
        for i in range(0, len(bitmap), 16)
    ]
    return "\n".join(
        [
            "// Generated by tools/gen_font.py from Nunito ExtraBold (SIL OFL 1.1). Do not edit.",
            '#include "font.h"',
            "",
            "static const uint8_t bitmap[] = {",
            *bitmap_lines,
            "};",
            "",
            "static const FontGlyph glyphs[] = {",
            *rows,
            "};",
            "",
            "const Font font_nunito = {",
            "    .bitmap = bitmap,",
            "    .glyphs = glyphs,",
            f"    .first_code = {FIRST_CODE},",
            f"    .last_code = {HEART_CODE},",
            f"    .ascent = {ascent},",
            f"    .line_height = {line_height},",
            "};",
            "",
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ttf", type=Path, required=True)
    parser.add_argument("--size", type=int, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    font = ImageFont.truetype(str(args.ttf), args.size)
    ascent, descent = font.getmetrics()
    args.out.write_text(to_c_source(build_glyphs(font), ascent, ascent + descent))


if __name__ == "__main__":
    main()
